def get_rezka_url(query: str) -> str:
    encoded = urllib.parse.quote(query)
    return f"https://rezka-ua.tv/search/?do=search&subaction=search&q={encoded}"

def get_random_movie(category: str = "horror") -> Dict[str, Any]:
    movies = MOVIES_DATABASE.get(category, MOVIES_DATABASE["horror"])
    movie = random.choice(movies)
    watch_url = get_rezka_url(movie["title"])
    return {
        **movie,
        "watch_url": watch_url
    }
